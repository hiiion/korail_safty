def recommend_rules(target, zone, work_type):
    """점검 대상·작업구역·작업 유형 → 자동 추천할 분야 규칙 집합 (아티팩트 recommendCats와 동일)."""
    t, z, w = target, zone, work_type
    rules = {"common"}
    if t == "철도차량" or w in ("차량 검수", "부품 점검 및 교체"):
        rules.add("vehicle")
    if t == "정비설비" or w in ("기계설비 정비", "부품 점검 및 교체", "중량물 취급"):
        rules.add("equip")
    if w == "중량물 취급":
        rules.add("heavy")
    if w == "전기·전자 작업" or z == "전기 작업장":
        rules.add("electric")
    if w == "용접 및 화기 작업" or z == "자재 보관소" or t == "공용시설" or w == "시설물 안전점검":
        rules.add("fire")
    return rules


